import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { analyze } from '../lib/engine/index';
import { EXAMPLES } from '../lib/examples';
import { createGroqProvider } from '../lib/llm/groq';
import { explainVerdict } from '../lib/llm/explain';
import { buildTemplateExplanation } from '../lib/llm/template';
import { toExplanationInput } from '../lib/llm/toExplanationInput';
import { isSafeExplanation } from '../lib/llm/validate';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'lib', 'examples.generated.ts');

async function main() {
  const provider = process.env.GROQ_API_KEY ? createGroqProvider() : undefined;
  const entries: Record<string, string> = {};

  for (const example of EXAMPLES) {
    const verdict = analyze(example.text);
    const input = toExplanationInput(verdict);
    const result = await explainVerdict(input, { provider });
    const text = isSafeExplanation(result.text)
      ? result.text
      : buildTemplateExplanation(input);

    entries[example.id] = text;
    console.log(`${example.id}: ${result.source}`);
  }

  const contents = `// Generated by scripts/precompute-explanations.ts. Do not edit by hand.\n\nexport const EXAMPLE_EXPLANATIONS: Record<string, string> = ${JSON.stringify(
    entries,
    null,
    2,
  )};\n`;

  await writeFile(output, contents);
  console.log(`wrote ${path.relative(root, output)}`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
